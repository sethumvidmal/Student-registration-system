/** Replaces every <i data-icon="..."> placeholder inside root with its SVG. */
function hydrateIcons(root = document) {
  root.querySelectorAll("i[data-icon]").forEach((placeholder) => {
    const size = Number(placeholder.dataset.size) || 16;
    placeholder.insertAdjacentHTML("afterend", icon(placeholder.dataset.icon, { size, className: placeholder.className }));
    placeholder.remove();
  });
}
